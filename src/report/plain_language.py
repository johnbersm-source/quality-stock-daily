def explain(component_name: str, points_awarded: float | None, max_points: float) -> str | None:
    """component_name에 매칭되는 규칙이 없으면 None을 반환(템플릿에서 조용히 생략)."""
    for key, what, (good, mid, bad) in _RULES:
        if key in component_name:
            if points_awarded is None:
                return what
            ratio = points_awarded / max_points if max_points else 0
            verdict = good if ratio >= 0.66 else (mid if ratio >= 0.33 else bad)
            return f"{what} {verdict}"
    return None
